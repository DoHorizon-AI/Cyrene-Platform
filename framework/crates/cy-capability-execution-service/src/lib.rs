#[derive(Debug, Clone)]
struct ApiError {
    code: capability_execution_error::Code,
    message: String,
}

impl ApiError {
    fn new(code: capability_execution_error::Code, message: impl Into<String>) -> Self {
        Self {
            code,
            message: message.into(),
        }
    }

    fn into_wire(self) -> CapabilityExecutionError {
        CapabilityExecutionError {
            code: self.code as i32,
            message: self.message,
        }
    }

    fn from_worker(error: WorkerTerminalError) -> Self {
        let code = match error {
            WorkerTerminalError::WorkerUnavailable(_) => {
                capability_execution_error::Code::CapabilityUnavailable
            }
            WorkerTerminalError::ActivationFailed(_) => {
                capability_execution_error::Code::ActivationFailed
            }
            WorkerTerminalError::ProtocolMismatch(_) => {
                capability_execution_error::Code::ProtocolMismatch
            }
            WorkerTerminalError::InvalidRequest(_) => {
                capability_execution_error::Code::InvalidRequest
            }
            WorkerTerminalError::CapabilityExecutionFailure(_) => {
                capability_execution_error::Code::ExecutionFailure
            }
            WorkerTerminalError::WorkerCrashed(_) => {
                capability_execution_error::Code::WorkerCrashed
            }
            WorkerTerminalError::Timeout(_) => capability_execution_error::Code::Timeout,
            WorkerTerminalError::Cancelled(_) => capability_execution_error::Code::Cancelled,
        };
        Self::new(code, error.to_string())
    }

    fn from_resolution(error: CapabilityResolutionError) -> Self {
        let code = match error {
            CapabilityResolutionError::NoProvider { .. }
            | CapabilityResolutionError::UnknownBinding { .. }
            | CapabilityResolutionError::BindingProviderUnavailable { .. } => {
                capability_execution_error::Code::CapabilityUnavailable
            }
            CapabilityResolutionError::InterfaceMismatch { .. }
            | CapabilityResolutionError::ExecutionModeMismatch { .. }
            | CapabilityResolutionError::BindingCapabilityMismatch { .. }
            | CapabilityResolutionError::AmbiguousBinding { .. } => {
                capability_execution_error::Code::InvalidRequest
            }
            CapabilityResolutionError::InvalidManifest { .. }
            | CapabilityResolutionError::InvalidBinding { .. }
            | CapabilityResolutionError::DuplicateManifest { .. }
            | CapabilityResolutionError::DuplicateBinding { .. } => {
                capability_execution_error::Code::ActivationFailed
            }
        };
        Self::new(code, error.to_string())
    }
}

fn parse_grpc_timeout(metadata: &MetadataMap) -> Result<Option<Duration>, String> {
    let Some(value) = metadata.get("grpc-timeout") else {
        return Ok(None);
    };
    let raw = value
        .to_str()
        .map_err(|_| "grpc-timeout metadata is not ASCII".to_string())?;
    if raw.len() < 2 || raw.len() > 9 {
        return Err("grpc-timeout metadata has invalid length".into());
    }
    let (digits, unit) = raw.split_at(raw.len() - 1);
    if digits.len() > 8 || digits.is_empty() {
        return Err("grpc-timeout value must contain at most eight digits".into());
    }
    let value = digits
        .parse::<u64>()
        .map_err(|_| "grpc-timeout value must be an unsigned integer".to_string())?;
    let duration = match unit {
        "H" => Duration::from_secs(value.saturating_mul(60 * 60)),
        "M" => Duration::from_secs(value.saturating_mul(60)),
        "S" => Duration::from_secs(value),
        "m" => Duration::from_millis(value),
        "u" => Duration::from_micros(value),
        "n" => Duration::from_nanos(value),
        _ => return Err("grpc-timeout metadata has an unsupported unit".into()),
    };
    Ok(Some(duration))
}

fn response_any(capability: &str, method: &str, result: WorkerInvocationResult) -> Any {
    let type_url = if result.payload_type_url.trim().is_empty() {
        format!("type.cyrene.io/capability/{capability}/{method}/response")
    } else {
        result.payload_type_url
    };
    Any {
        type_url,
        value: result.payload,
    }
}

fn event_any(value: Vec<u8>, type_url: String) -> Any {
    Any {
        type_url: if type_url.trim().is_empty() {
            OPAQUE_PAYLOAD_TYPE_URL.to_string()
        } else {
            type_url
        },
        value,
    }
}

fn event_item(
    public_subscription_id: &str,
    binding_id: Option<&str>,
    event: WorkerApplicationEvent,
) -> CapabilityEventStreamItem {
    CapabilityEventStreamItem {
        item: Some(capability_event_stream_item::Item::ApplicationEvent(
            CapabilityApplicationEvent {
                subscription_id: public_subscription_id.to_string(),
                capability: event.capability,
                event_sequence: event.event_sequence,
                event_type: event.event_type,
                payload: Some(event_any(event.payload, event.payload_type_url)),
                generation: event.generation,
                source_id: event.source_id,
                binding_id: binding_id.unwrap_or_default().to_string(),
            },
        )),
    }
}

impl StreamEndContext {
    fn item(
        &self,
        generation: u64,
        reason: i32,
        message: impl Into<String>,
        error: Option<CapabilityExecutionError>,
    ) -> CapabilityEventStreamItem {
        CapabilityEventStreamItem {
            item: Some(capability_event_stream_item::Item::StreamEnd(
                CapabilityEventStreamEnd {
                    subscription_id: self.subscription_id.clone(),
                    capability: self.capability.clone(),
                    generation,
                    source_id: self.source_id.clone(),
                    binding_id: self.binding_id.clone(),
                    reason,
                    message: message.into(),
                    error,
                },
            )),
        }
    }
}

fn send_terminal(
    permit: &mut Option<OwnedPermit<Result<CapabilityEventStreamItem, Status>>>,
    item: CapabilityEventStreamItem,
) {
    if let Some(permit) = permit.take() {
        permit.send(Ok(item));
    }
}

fn stream_end_from_termination(
    termination: &ApplicationEventStreamTermination,
) -> (i32, Option<CapabilityExecutionError>) {
    let (reason, error_code) = match termination.reason {
        ApplicationEventStreamEndReason::NormalCompletion => {
            (stream_reason::NORMAL_COMPLETION, None)
        }
        ApplicationEventStreamEndReason::Cancelled => (
            stream_reason::CANCELLED,
            Some(capability_execution_error::Code::Cancelled),
        ),
        ApplicationEventStreamEndReason::WorkerUnavailable => (
            stream_reason::CAPABILITY_UNAVAILABLE,
            Some(capability_execution_error::Code::CapabilityUnavailable),
        ),
        ApplicationEventStreamEndReason::WorkerCrash => (
            stream_reason::WORKER_CRASH,
            Some(capability_execution_error::Code::WorkerCrashed),
        ),
        ApplicationEventStreamEndReason::ProtocolFailure => (
            stream_reason::PROTOCOL_FAILURE,
            Some(capability_execution_error::Code::ProtocolMismatch),
        ),
        ApplicationEventStreamEndReason::GenerationTerminated => (
            stream_reason::GENERATION_TERMINATED,
            Some(capability_execution_error::Code::GenerationTerminated),
        ),
        ApplicationEventStreamEndReason::Backpressure => (
            stream_reason::BACKPRESSURE,
            Some(capability_execution_error::Code::Backpressure),
        ),
    };
    (
        reason,
        error_code.map(|code| ApiError::new(code, termination.message.clone()).into_wire()),
    )
}

fn stream_reason_for_error(code: capability_execution_error::Code) -> i32 {
    match code {
        capability_execution_error::Code::CapabilityUnavailable
        | capability_execution_error::Code::ActivationFailed => {
            stream_reason::CAPABILITY_UNAVAILABLE
        }
        capability_execution_error::Code::ProtocolMismatch => stream_reason::PROTOCOL_FAILURE,
        capability_execution_error::Code::WorkerCrashed => stream_reason::WORKER_CRASH,
        capability_execution_error::Code::Cancelled => stream_reason::CANCELLED,
        capability_execution_error::Code::Backpressure => stream_reason::BACKPRESSURE,
        capability_execution_error::Code::GenerationTerminated => {
            stream_reason::GENERATION_TERMINATED
        }
        capability_execution_error::Code::Unspecified
        | capability_execution_error::Code::InvalidRequest
        | capability_execution_error::Code::ExecutionFailure
        | capability_execution_error::Code::Timeout
        | capability_execution_error::Code::StreamTerminated => stream_reason::UNSPECIFIED,
    }
}

mod stream_reason {
    pub const UNSPECIFIED: i32 = 0;
    pub const NORMAL_COMPLETION: i32 = 1;
    pub const CANCELLED: i32 = 2;
    pub const CAPABILITY_UNAVAILABLE: i32 = 3;
    pub const WORKER_CRASH: i32 = 4;
    pub const PROTOCOL_FAILURE: i32 = 5;
    pub const GENERATION_TERMINATED: i32 = 6;
    pub const BACKPRESSURE: i32 = 7;
}

